from google import genai

from app.config.settings import Settings
from app.discovery.feeds import discover_topics

settings = Settings()

DATE = settings.DATE

def rank_topics() -> list:
    """
    Rank the discovered trending topics in the software development industry based on their relevance, engagement potential, and overall quality.
    This function will rank the list of 10 engaging and informative post ideas generated by the discover_topics function using Google Gemini AI.
    """

    # Discover the current trending topics in the software development industry.
    topics = discover_topics()

    PROMPT = f"""
                Role: Assume you are a very famous person on the LinkedIn and X(Twitter) platforms. 
                Also you are a Software Engineer with 2+ years of experience in the field 
                of software development. You post contents generally related to the software development 
                field like System Design, Data Structures and Algorithms, Full Stack Development, etc. 
                and you have a large following of people who are interested in your posts. You excatly
                know what your audience wants to read and engage with. You are an expert in the field of 
                software development and you have a deep understanding of the current trends in the industry.

                Task: Rank the list of post ideas that I am providing, based on their relevance, engagement potential, 
                and overall quality. The ranking should be done in a way that the most relevant and engaging post ideas 
                are ranked higher, while the less relevant and engaging post ideas are ranked lower. You should also 
                provide a brief explanation for each ranking, explaining why the post idea was ranked in that particular 
                position. The ranking should be done in a way that it is easy for your audience to understand and
                engage with the post ideas.

                Point to Note: The ranking should be done in a list format, with each post idea numbered from 1 to 10.
                Use less tokens as possible to generate the output. The ranking should be based on the current date ${DATE} 
                trends in the software development industry. The brief explanations for each ranking should be concise and to the point, 
                highlighting the key aspects of the post idea and why it was ranked in that particular position.

                Output Format: The output should be a JSON array of objects, where each object represents a ranked post idea.
                Each object should have the following properties:
                - "title": A string representing the title of the post idea.
                - "description": A string representing a brief description of the post idea, explaining what the post will be about and why it would be interesting to your audience.
                - "rank": An integer representing the rank of the post idea, with 1 being the highest rank and 10 being the lowest rank.
                - "explanation": A string representing a brief explanation for the ranking, explaining why the post idea was ranked in that particular position.
                """

    client = genai.Client(api_key=settings.GEMINI_API_KEY)

    response = client.interactions.create(
        model="gemini-3.8-flash",
        input=PROMPT
    )

    print(response.output_text)

rank_topics()
